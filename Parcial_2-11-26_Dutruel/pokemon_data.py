def _debilidades(tipos):
    debilidades = []
    for atacante, (fuertes, resistidos, inmunes) in _EFECTIVIDAD.items():
        multiplicador = 1
        for defensor in tipos:
            if defensor in inmunes:
                multiplicador = 0
                break
            if defensor in fuertes:
                multiplicador *= 2
            elif defensor in resistidos:
                multiplicador /= 2
        if multiplicador > 1:
            debilidades.append(_TIPOS[atacante])
    return debilidades


